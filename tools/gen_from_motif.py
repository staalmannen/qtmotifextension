#!/usr/bin/env python3
"""Generate resource tables and enum-name lists from the Motif sources.

Inputs are the LGPL Motif 2.3 sources/headers and the MIT-licensed Xt/Xlib
headers; outputs are committed so building never needs Motif or X11.

usage: gen_from_motif.py <motif-src-dir> <installed-include-dir> <repo-dir>
"""
import os, re, sys, glob

motif, inc, repo = sys.argv[1:4]
xmh = os.path.join(inc, "Xm")
out_gen = os.path.join(repo, "src", "generated")
os.makedirs(out_gen, exist_ok=True)

def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)

HDR = """/* Generated by tools/gen_from_motif.py from %s.
 * The source is %s; see the LICENSE files. Do not edit. */
"""

public = [h for h in sorted(glob.glob(os.path.join(xmh, "*.h")))
          if not re.search(r"(P|T|I)\.h$", h) and os.path.basename(h) not in
          ("XmStrDefs.h", "XmStrDefs22.h", "XmStrDefs23.h", "XmAll.h", "Xmfuncs.h", "XmosP.h", "Print.h", "PrintSP.h",
           "Xmos.h", "Xpmos.h", "XpmP.h", "XmPrint.h", "Xmos_r.h", "XmIm.h", "VaSimple.h", "XmP.h")]

# ---------------------------------------------------------------- resources
rows = []
def class_name(src):
    m = re.search(r'ClassRec\s+\w+\s*=\s*\{.*?"(Xm\w+|\w+Shell)"', src, re.S)
    return m.group(1) if m else None

for c in sorted(glob.glob(os.path.join(motif, "lib", "Xm", "*.c"))):
    src = strip_comments(open(c).read())
    cls = class_name(src)
    if not cls: continue
    for arr in re.finditer(r"static\s+XtResource\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\n\s*\}\s*;", src, re.S):
        kind = "constraint" if "constraint" in arr.group(1).lower() else "normal"
        for r in re.finditer(r"\{\s*(XmN\w+|XtN\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*sizeof\s*\(([^)]*)\)\s*,[^,]*\([^)]*\)[^,]*,\s*(\w+)\s*,\s*([^}]*?)\s*\}",
                             arr.group(2), re.S):
            name, rclass, rtype, size, dtype, dval = [x.strip() for x in r.groups()]
            dval = re.sub(r"\s+", " ", dval).rstrip(", ")
            rows.append((cls, kind, name, rclass, rtype, size, dtype, dval))

# Identifiers the vendored public headers define; anything else is Motif-private.
known = set()
for h in glob.glob(os.path.join(repo, "include", "**", "*.h"), recursive=True):
    known.update(re.findall(r"\b[A-Za-z_]\w*\b", open(h, errors="replace").read()))
known.update(["sizeof", "unsigned", "int", "char", "short", "long", "NULL", "True", "False"])
def ok_ids(expr):
    return all(t in known for t in re.findall(r"\b[A-Za-z_]\w*\b", expr))
# Resource names/classes/types that only Motif's private headers define
# (e.g. XmRPositionValue in SpinBP.h) are plain string literals: use those.
private_strings = {}
for h in glob.glob(os.path.join(motif, "lib", "Xm", "*.h")):
    for m in re.finditer(r'^#\s*define\s+(X[mt][NCR]\w+)\s+("[^"]*")\s*$', open(h, errors="replace").read(), re.M):
        private_strings.setdefault(m.group(1), m.group(2))
def literal(ident):
    return private_strings[ident] if ident not in known and ident in private_strings else ident
rows = [r[:2] + (literal(r[2]), literal(r[3]), literal(r[4])) + r[5:] for r in rows]
def ok_field(expr):
    return expr.startswith('"') or ok_ids(expr)
rows = [r for r in rows if ok_field(r[2]) and ok_field(r[3]) and ok_field(r[4]) and ok_ids(r[5])]
def ok_default(expr):
    return ok_ids(expr) and all(re.match(r"^(Xm|Xt|X[A-Z]|True$|False$|NULL$|sizeof$|unsigned$|int$|char$|short$|long$|Pixel$|Pixmap$|Dimension$|Position$|Boolean$|Cardinal$|String$|Widget$|XtPointer$)", t)
               for t in re.findall(r"\b[A-Za-z_]\w*\b", expr))
rows = [r[:7] + ((r[7] if ok_default(r[7]) else "0"),) for r in rows]

with open(os.path.join(out_gen, "resources.inc"), "w") as f:
    f.write("// " + (HDR % ("Motif 2.3 lib/Xm/*.c XtResource tables", "LGPL 2.1 Motif")).replace("\n", "\n// ") + "\n")
    for cls, kind, name, rclass, rtype, size, dtype, dval in rows:
        dv = dval if dtype in ("XmRImmediate", "XtRImmediate") else "0"
        ds = re.sub(r"^\(\s*\w+\s*\)\s*", "", dval) if dtype in ("XmRString", "XtRString") else "nullptr"
        if not ds.startswith('"') and ds != "nullptr": ds = "nullptr"
        f.write('RES ("%s", %s, %s, %s, %s, sizeof (%s), %s, %s, %s)\n' %
                (cls, "true" if kind == "constraint" else "false", name, rclass, rtype, size, dtype, dv, ds))
print("resources", len(rows), "classes", len(set(r[0] for r in rows)))

# ---------------------------------------------------------------- enum names
# Names only: the C++ compiler takes the values from the vendored headers, and
# drops (via a constexpr check) anything that is not an integer constant.
names = []
for h in sorted(glob.glob(os.path.join(repo, "include", "Xm", "*.h"))):
    s = strip_comments(open(h).read())
    for m in re.finditer(r"enum\s*\w*\s*\{([^{}]*)\}", s):
        for e in m.group(1).split(","):
            n = e.split("=")[0].strip()
            if re.match(r"^Xm[A-Z0-9_]+$", n) and n not in names: names.append(n)
    for m in re.finditer(r"^\s*#\s*define\s+(Xm[A-Z][A-Z0-9_]+)[ \t]+[^\n]+$", s, re.M):
        if m.group(1) not in names: names.append(m.group(1))
with open(os.path.join(out_gen, "enums.inc"), "w") as f:
    f.write("// Generated by tools/gen_from_motif.py: Motif enum/constant names. Do not edit.\n")
    for n in names:
        f.write("ENUM (%s)\n" % n)
print("enum names", len(names))

# ---------------------------------------------------------------- keysym names
ks = []
for m in re.finditer(r"^#define XK_(\w+)\s+0x[0-9a-fA-F]+", open(os.path.join(repo, "include", "X11", "keysymdef.h")).read(), re.M):
    if m.group(1) not in ks: ks.append(m.group(1))
with open(os.path.join(out_gen, "keysyms.inc"), "w") as f:
    f.write("// Generated by tools/gen_from_motif.py from X11/keysymdef.h (MIT). Do not edit.\n")
    for n in ks:
        f.write("#ifdef XK_%s\nKS (\"%s\", XK_%s)\n#endif\n" % (n, n, n))
print("keysyms", len(ks))
