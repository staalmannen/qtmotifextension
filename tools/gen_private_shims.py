#!/usr/bin/env python3
"""Write the compatibility versions of Motif's and Xt's private headers.

Programs often include <Xm/XmP.h>, <X11/IntrinsicP.h> or <Xm/DrawingAP.h>
without using any widget internals. These shims let such programs compile:
each includes the matching public header. Widget records are not exposed, so
code that reads widget structs fails to compile instead of misbehaving.

usage: gen_private_shims.py <motif-src-dir> <repo-dir>
"""
import glob, os, sys

motif, repo = sys.argv[1:3]
NOTE = "/* Motif on Qt compatibility header: the public API only, no widget internals.\n * Generated by tools/gen_private_shims.py. */\n"

for p in sorted(glob.glob(os.path.join(motif, "lib", "Xm", "*P.h"))):
    name = os.path.basename(p)
    if name in ("XmP.h",): continue
    public = name[:-3] + ".h"
    guard = "MQ_SHIM_XM_" + name[:-2].upper()
    body = '#include <Xm/XmP.h>\n'
    if os.path.exists(os.path.join(repo, "include", "Xm", public)):
        body += '#include <Xm/%s>\n' % public
    out = os.path.join(repo, "include", "Xm", name)
    if os.path.exists(out) and "gen_private_shims" not in open(out).read(): continue
    with open(out, "w") as f:
        f.write(NOTE + "#ifndef %s\n#define %s\n%s#endif\n" % (guard, guard, body))

for name, public in (("CoreP.h", "Core.h"), ("CompositeP.h", "Composite.h"), ("ConstrainP.h", "Constraint.h"),
                     ("ObjectP.h", "Object.h"), ("RectObjP.h", "RectObj.h"), ("ShellP.h", "Shell.h"), ("VendorP.h", None)):
    guard = "MQ_SHIM_X11_" + name[:-2].upper()
    body = "#include <X11/IntrinsicP.h>\n" + ("#include <X11/%s>\n" % public if public else "")
    with open(os.path.join(repo, "include", "X11", name), "w") as f:
        f.write(NOTE + "#ifndef %s\n#define %s\n%s#endif\n" % (guard, guard, body))
