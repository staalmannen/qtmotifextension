#!/usr/bin/env python3
"""Install Motif's private headers (<Xm/LabelP.h>, <Xm/PushBP.h> ...).

Programs subclass Motif widgets (Xlt's BubbleButton is an XmPushButton) and
read widget records through the private headers' macros (Lab_Font ...). The
genuine headers are installed, and the library allocates every widget with
the real record size (src/xm_records.cpp), so instance parts sit where the
program's compiler puts them.

The few private headers that need Motif's internal headers get a shim that
includes the public API only: code that reads those records fails to compile
instead of misbehaving.

X11's private headers (IntrinsicP.h, CoreP.h ...) are the genuine ones and
are not touched.

usage: gen_private_shims.py <motif-src-dir> <repo-dir>
"""
import glob, os, shutil, sys

motif, repo = sys.argv[1:3]
NOTE = "/* Motif on Qt compatibility header: the public API only, no widget internals.\n * Generated by tools/gen_private_shims.py. */\n"
# need Motif's internal headers (TextFI.h, PrintSI.h ...)
SHIMS = {"DataFP.h", "PrintSP.h", "TextFP.h"}

# trait headers the private headers include (ScrolledWP.h, TransferP.h)
for name in ("NavigatorT.h", "ScrollFrameT.h", "TransferT.h"):
    shutil.copyfile(os.path.join(motif, "lib", "Xm", name), os.path.join(repo, "include", "Xm", name))

for p in sorted(glob.glob(os.path.join(motif, "lib", "Xm", "*P.h"))):
    name = os.path.basename(p)
    out = os.path.join(repo, "include", "Xm", name)
    if name in SHIMS:
        public = name[:-3] + ".h"
        guard = "MQ_SHIM_XM_" + name[:-2].upper()
        body = '#include <Xm/XmP.h>\n'
        if os.path.exists(os.path.join(repo, "include", "Xm", public)):
            body += '#include <Xm/%s>\n' % public
        with open(out, "w") as f:
            f.write(NOTE + "#ifndef %s\n#define %s\n%s#endif\n" % (guard, guard, body))
    else:
        shutil.copyfile(p, out)
